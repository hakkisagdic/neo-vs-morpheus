const TERMINAL = 256;

// Decoding trie: tree[node * 2 + bit] is the next node, or -(symbol + 1) at a leaf.
const tree: Int32Array = (() => {
  const nodes: number[] = [0, 0];
  for (let symbol = 0; symbol <= TERMINAL; symbol++) {
    const length = TABLE[symbol * 2];
    const code = TABLE[symbol * 2 + 1];
    let node = 0;
    for (let i = length - 1; i >= 0; i--) {
      const slot = node * 2 + ((code >> i) & 1);
      if (i === 0) {
        nodes[slot] = -(symbol + 1);
      } else {
        if (nodes[slot] === 0) {
          nodes[slot] = nodes.length / 2;
          nodes.push(0, 0);
        }
        node = nodes[slot];
      }
    }
  }
  return Int32Array.from(nodes);
})();

/** Streaming decoder: feed raw socket bytes, get back complete decompressed chunks. */
export class HuffmanDecoder {
  #node = 0;
  #out: number[] = [];

  push(input: Uint8Array): Uint8Array[] {
    const chunks: Uint8Array[] = [];
    for (let i = 0; i < input.length; i++) {
      const byte = input[i];
      for (let bit = 7; bit >= 0; bit--) {
        const next = tree[this.#node * 2 + ((byte >> bit) & 1)];
        if (next > 0) {
          this.#node = next;
          continue;
        }
        this.#node = 0;
        const symbol = -next - 1;
        if (symbol === TERMINAL) {
          chunks.push(Uint8Array.from(this.#out));
          this.#out = [];
          break; // the rest of this byte is padding
        }
        this.#out.push(symbol);
      }
    }
    return chunks;
  }
}

/** Compresses one packet the way the server does (used by tests and the fake server). */
export function huffmanCompress(input: Uint8Array): Uint8Array {
  const out: number[] = [];
  let bits = 0;
  let count = 0;
  const emit = (symbol: number) => {
    const length = TABLE[symbol * 2];
    bits = (bits << length) | TABLE[symbol * 2 + 1];
    count += length;
    while (count >= 8) {
      count -= 8;
      out.push((bits >> count) & 0xff);
    }
    bits &= (1 << count) - 1;
  };
  for (const byte of input) {
    emit(byte);
  }
  emit(TERMINAL);
  if (count > 0) {
    out.push((bits << (8 - count)) & 0xff);
  }
  return Uint8Array.from(out);
}
