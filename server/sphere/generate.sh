#!/bin/sh
# Writes the part of the arena scripts that comes from outside the image: the arena's place
# (from the environment) and the character templates (templates/*.json, mounted read-only), as
# Sphere script. The entrypoint runs it at every start; scripts/neo_arena.scp uses what it writes.
#
#   generate.sh <templates folder> <output .scp>
#
#   NEO_ARENA_MAP (Felucca), NEO_ARENA_X (1180), NEO_ARENA_Y (3610)   slot 0's centre, as on ModernUO
#   NEO_REAGENTS (200)   reagents of each kind for the built-in mage (used when there is no mage.json)
#
# Sphere script cannot read JSON, so every template becomes a branch of one function,
# f_neo_tpl <template>,<step>,<skill>, with ModernUO's skill and item names turned into Sphere's.
# A name with no translation is used as it is, so a template may name a Sphere defname or item id.
set -eu

dir=${1:?usage: generate.sh <templates folder> <output .scp>}
out=${2:?usage: generate.sh <templates folder> <output .scp>}

fail() {
  echo "generate.sh: $*" >&2
  exit 1
}

number() { case "$2" in '' | *[!0-9]*) fail "$1 must be a whole number, got '$2'" ;; esac; }

map_name=${NEO_ARENA_MAP:-Felucca}
case "$(printf '%s' "$map_name" | tr '[:upper:]' '[:lower:]')" in
  felucca) map=0 map_name=Felucca ;;
  trammel) map=1 map_name=Trammel ;;
  ilshenar) map=2 map_name=Ilshenar ;;
  malas) map=3 map_name=Malas ;;
  tokuno) map=4 map_name=Tokuno ;;
  termur) map=5 map_name=TerMur ;;
  *) fail "NEO_ARENA_MAP must be Felucca, Trammel, Ilshenar, Malas, Tokuno or TerMur, got '$map_name'" ;;
esac
x=${NEO_ARENA_X:-1180}
y=${NEO_ARENA_Y:-3610}
reagents=${NEO_REAGENTS:-200}
number NEO_ARENA_X "$x"
number NEO_ARENA_Y "$y"
number NEO_REAGENTS "$reagents"

# The template files, by the names the bot uses (templates.ts: lower-case letters, digits, -).
# One that is not valid JSON is left out rather than keeping the shard from starting.
set --
skipped=""
if [ -d "$dir" ]; then
  for file in "$dir"/*.json; do
    [ -f "$file" ] || continue
    case "$(basename "$file" .json)" in
      *[!a-z0-9-]* | '') skipped="$skipped $(basename "$file") (name)" ;;
      *)
        if jq -e 'type == "object"' "$file" > /dev/null 2>&1; then
          set -- "$@" "$file"
        else
          skipped="$skipped $(basename "$file") (not a JSON object)"
        fi
        ;;
    esac
  done
fi
[ -z "$skipped" ] || echo "generate.sh: skipped templates:$skipped" >&2
# No template files: jq reads nothing (rather than its standard input) and only the built-in mage remains.
[ $# -gt 0 ] || set -- /dev/null

tmp="$out.tmp"
{
  cat <<EOF
//****************************************************************************
// Generated by server/sphere/generate.sh at the container's start from the environment and
// templates/*.json. Edits here are lost: change those instead and restart the container.
//****************************************************************************
VERSION=X1

[DEFNAME neo_settings]
// The centre of arena slot 0 (NEO_ARENA_MAP, NEO_ARENA_X, NEO_ARENA_Y); slot n is 80*n tiles east.
neo_arena_map		$map
neo_arena_mapname	$map_name
neo_arena_x		$x
neo_arena_y		$y

[FUNCTION f_neo_tpl]
// f_neo_tpl <template>,<step>,<skill>: one step of a character template, run on the player.
// Returns 1 when the template exists. Steps (scripts/neo_arena.scp has the functions they call):
//   apply   stats, and skills in Sphere's keys (each at <skill> instead when that is 0 or more)
//   gear    what it wears
//   check   whether its consumables exist on this shard
//   stock   its consumables, and a full spellbook if it has one
EOF
  # jq reads every template (none: just the built-in mage) and writes one branch for each.
  jq -n -r --argjson reagents "$reagents" '
    # ModernUO SkillName -> Sphere skill key (Scripts-X skills/*.scp), in the same order (0-57).
    def skills: {
      Alchemy: "Alchemy", Anatomy: "Anatomy", AnimalLore: "AnimalLore", ItemID: "ItemID",
      ArmsLore: "ArmsLore", Parry: "Parrying", Begging: "Begging", Blacksmith: "Blacksmithing",
      Fletching: "Bowcraft", Peacemaking: "Peacemaking", Camping: "Camping", Carpentry: "Carpentry",
      Cartography: "Cartography", Cooking: "Cooking", DetectHidden: "DetectingHidden",
      Discordance: "Enticement", EvalInt: "EvaluatingIntel", Healing: "Healing", Fishing: "Fishing",
      Forensics: "Forensics", Herding: "Herding", Hiding: "Hiding", Provocation: "Provocation",
      Inscribe: "Inscription", Lockpicking: "Lockpicking", Magery: "Magery",
      MagicResist: "MagicResistance", Tactics: "Tactics", Snooping: "Snooping",
      Musicianship: "Musicianship", Poisoning: "Poisoning", Archery: "Archery",
      SpiritSpeak: "SpiritSpeak", Stealing: "Stealing", Tailoring: "Tailoring",
      AnimalTaming: "Taming", TasteID: "TasteID", Tinkering: "Tinkering", Tracking: "Tracking",
      Veterinary: "Veterinary", Swords: "Swordsmanship", Macing: "Macefighting", Fencing: "Fencing",
      Wrestling: "Wrestling", Lumberjacking: "Lumberjacking", Mining: "Mining",
      Meditation: "Meditation", Stealth: "Stealth", RemoveTrap: "RemoveTrap",
      Necromancy: "Necromancy", Focus: "Focus", Chivalry: "Chivalry", Bushido: "Bushido",
      Ninjitsu: "Ninjitsu", Spellweaving: "Spellweaving", Mysticism: "Mysticism",
      Imbuing: "Imbuing", Throwing: "Throwing"
    };
    # ModernUO item class -> Sphere item. Weapons, shields and the leather sleeves by ModernUO
    # graphic, which the bot knows them by (src/game/items.ts); Scripts-X defines several of
    # them on the other graphic of the pair (i_katana is 013fe, i_bow 013b1).
    def items: {
      BlackPearl: "i_reag_black_pearl", Bloodmoss: "i_reag_blood_moss", Garlic: "i_reag_garlic",
      Ginseng: "i_reag_ginseng", MandrakeRoot: "i_reag_mandrake_root", Nightshade: "i_reag_nightshade",
      SpidersSilk: "i_reag_spider_silk", SulfurousAsh: "i_reag_sulfur_ash",
      Bandage: "i_bandage", Arrow: "i_arrow", Bolt: "01bfb",
      GreaterHealPotion: "i_potion_HealGreat", HealPotion: "i_potion_Heal", LesserHealPotion: "i_potion_HealLess",
      GreaterCurePotion: "i_potion_CureGreat", CurePotion: "i_potion_Cure", LesserCurePotion: "i_potion_CureLess",
      TotalRefreshPotion: "i_potion_RefreshTotal", RefreshPotion: "i_potion_Refresh",
      GreaterExplosionPotion: "i_potion_ExplosionGreat", ExplosionPotion: "i_potion_Explosion",
      LesserExplosionPotion: "i_potion_ExplosionLess",
      GreaterStrengthPotion: "i_potion_StrengthGreat", StrengthPotion: "i_potion_Strength",
      GreaterAgilityPotion: "i_potion_AgilityGreat", AgilityPotion: "i_potion_Agility",
      NightSightPotion: "i_potion_Nightsight",
      Katana: "013ff", Broadsword: "0f5e", Longsword: "0f61", Kryss: "01401", WarFork: "01405",
      Dagger: "0f52", Halberd: "0143e", Bow: "013b2", Crossbow: "0f50", HeaterShield: "01b76",
      LeatherChest: "i_leather_tunic", LeatherLegs: "i_leather_leggings", LeatherArms: "013cd",
      LeatherGloves: "i_leather_gloves", LeatherGorget: "i_leather_gorget", LeatherCap: "i_leather_cap",
      Spellbook: "i_spellbook", Robe: "i_robe"
    };
    # Names as ModernUO resolves them: in any case.
    def lower_keys: with_entries(.key |= ascii_downcase);
    def skill_key($name): (skills | lower_keys)[$name | ascii_downcase]
      // ([skills[] | select(ascii_downcase == ($name | ascii_downcase))] | first);
    def item_id($name): (items | lower_keys)[$name | ascii_downcase] // $name;
    # A word Sphere reads as one argument: no spaces, commas, brackets or comment marks.
    def word: tostring | gsub("[^A-Za-z0-9_.-]"; "_");
    def clamp($lo; $hi): if . < $lo then $lo elif . > $hi then $hi else . end;
    def stat($name): (.stats[$name] // 50 | floor | clamp(10; 125) | tostring);

    def branch($id):
      . as $t
      | ($t.skills // {} | to_entries) as $skills
      | ($t.wear // []) as $wear
      | ($t.pack // {} | to_entries) as $pack
      | [
          "IF (STRCMPI(<ARGV[0]>,\($id)) == 0)",
          "\t// \(($t.title // $id) | tostring | gsub("[\r\n]"; " "))",
          "\tIF (STRCMPI(<ARGV[1]>,apply) == 0)",
          "\t\tf_neo_stats \($t | stat("str")),\($t | stat("dex")),\($t | stat("int"))",
          ($skills[] | (.key | word) as $n | skill_key($n) as $k
            | if $k then "\t\tf_neo_skill \($k),\(.value | floor | clamp(0; 120)),<ARGV[2]>"
              else "\t\tf_neo_problem unknown skill \($n)" end),
          "\tELIF (STRCMPI(<ARGV[1]>,gear) == 0)",
          ($wear[] | word as $n | "\t\tf_neo_wear \(item_id($n)),\($n)"),
          "\tELIF (STRCMPI(<ARGV[1]>,check) == 0)",
          ($pack[] | (.key | word) as $n | "\t\tf_neo_check \(item_id($n)),\($n)"),
          "\tELIF (STRCMPI(<ARGV[1]>,stock) == 0)",
          ($pack[] | (.key | word) as $n | "\t\tf_neo_stock \(item_id($n)),\(.value | floor | clamp(1; 60000))"),
          (if $t.spellbook then "\t\tf_neo_book" else empty end),
          "\tENDIF",
          "\tRETURN 1",
          "ENDIF"
        ]
      | join("\n");

    # The mage every bot starts as, used when templates/mage.json does not exist (as on ModernUO).
    def builtin_mage: {
      title: "PvP mage (built in)", stats: {str: 90, dex: 35, int: 100},
      skills: {Magery: 100, EvalInt: 100, Meditation: 100, MagicResist: 100, Wrestling: 100, Inscribe: 100, Poisoning: 100},
      pack: ([ "BlackPearl", "Bloodmoss", "Garlic", "Ginseng", "MandrakeRoot", "Nightshade", "SpidersSilk", "SulfurousAsh" ]
        | map({key: ., value: $reagents}) | from_entries),
      spellbook: true
    };

    [inputs | {id: (input_filename | split("/") | last | rtrimstr(".json")), t: .}]
    | (if any(.id == "mage") then . else . + [{id: "mage", t: builtin_mage}] end)
    | map(. as $e | $e.t | branch($e.id))
    | join("\n")
  ' "$@"
  echo "RETURN 0"
} > "$tmp"
mv "$tmp" "$out"
